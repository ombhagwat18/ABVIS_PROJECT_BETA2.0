"""
Stage 2D-B — YOLO Export Script
================================
Reads:
  - stage2_dataset/annotations.json
  - stage2_dataset/split.json
  - stage2_dataset/clean/<image files>

Writes (WITHOUT touching source files):
  - stage2_dataset/yolo_export/
        images/train|val|test/
        labels/train|val|test/
        data.yaml

Usage:
    python stage2_dataset/export_yolo.py
"""

import json
import os
import shutil
import sys
import datetime

# ── Paths ──────────────────────────────────────────────────────────────────────
SCRIPT_DIR   = os.path.dirname(os.path.abspath(__file__))
STAGE2_DIR   = SCRIPT_DIR                               # stage2_dataset/
CLEAN_DIR    = os.path.join(STAGE2_DIR, "clean")
ANNOT_PATH   = os.path.join(STAGE2_DIR, "annotations.json")
SPLIT_PATH   = os.path.join(STAGE2_DIR, "split.json")
EXPORT_DIR   = os.path.join(STAGE2_DIR, "yolo_export")

# ── Class map ─────────────────────────────────────────────────────────────────
CLASS_ORDER = ["bottle", "cap", "label"]
CLS_TO_ID   = {name: idx for idx, name in enumerate(CLASS_ORDER)}

# ── Expected totals (for sanity check during export) ──────────────────────────
EXPECTED = {
    "train": 418,
    "val":    89,
    "test":   87,
    "total": 594,
    "boxes": 1994,
}

def load_json(path):
    with open(path, "r", encoding="utf-8") as f:
        return json.load(f)

def build_split_map(split_data):
    """Return {filename: split_name} mapping from split.json."""
    mapping = {}
    for split_name, split_info in split_data["splits"].items():
        for scene_id, files in split_info["files_by_scene"].items():
            for fname in files:
                if fname in mapping:
                    raise ValueError(
                        f"Duplicate: '{fname}' appears in both "
                        f"'{mapping[fname]}' and '{split_name}'"
                    )
                mapping[fname] = split_name
    return mapping

def create_dirs():
    """Create the yolo_export directory tree."""
    for split in ("train", "val", "test"):
        os.makedirs(os.path.join(EXPORT_DIR, "images",  split), exist_ok=True)
        os.makedirs(os.path.join(EXPORT_DIR, "labels",  split), exist_ok=True)
    print(f"[DIR] Created export tree under: {EXPORT_DIR}")

def write_data_yaml():
    """Write data.yaml (absolute paths so Ultralytics always resolves them)."""
    # Ultralytics prefers forward-slash paths
    train_path = os.path.join(EXPORT_DIR, "images", "train").replace("\\", "/")
    val_path   = os.path.join(EXPORT_DIR, "images", "val").replace("\\", "/")
    test_path  = os.path.join(EXPORT_DIR, "images", "test").replace("\\", "/")

    yaml_content = f"""# Stage 2 — Bottle detection dataset
# Auto-generated by export_yolo.py — DO NOT EDIT MANUALLY

path: {EXPORT_DIR.replace(chr(92), "/")}

train: images/train
val:   images/val
test:  images/test

nc: {len(CLASS_ORDER)}
names: {CLASS_ORDER}
"""
    yaml_path = os.path.join(EXPORT_DIR, "data.yaml")
    with open(yaml_path, "w", encoding="utf-8") as f:
        f.write(yaml_content)
    print(f"[YAML] Written: {yaml_path}")
    return yaml_path

def export(annotations, split_map):
    """Copy images and write label files. Returns statistics dict."""
    stats = {
        "counts":        {"train": 0, "val": 0, "test": 0},
        "box_counts":    {
            "train": {"bottle": 0, "cap": 0, "label": 0, "total": 0},
            "val":   {"bottle": 0, "cap": 0, "label": 0, "total": 0},
            "test":  {"bottle": 0, "cap": 0, "label": 0, "total": 0},
        },
        "class_totals":  {"bottle": 0, "cap": 0, "label": 0},
        "missing_images": [],
        "missing_from_split": [],
        "errors": [],
    }

    images_data = annotations["images"]

    for fname, split_name in split_map.items():
        src_img = os.path.join(CLEAN_DIR, fname)

        # Check source image exists
        if not os.path.isfile(src_img):
            stats["missing_images"].append(fname)
            stats["errors"].append(f"MISSING SOURCE: {fname}")
            continue

        # Check annotation exists
        if fname not in images_data:
            stats["missing_from_split"].append(fname)
            stats["errors"].append(f"NO ANNOTATION: {fname}")
            continue

        # Copy image
        dst_img = os.path.join(EXPORT_DIR, "images", split_name, fname)
        shutil.copy2(src_img, dst_img)

        # Write label file
        stem     = os.path.splitext(fname)[0]
        lbl_path = os.path.join(EXPORT_DIR, "labels", split_name, stem + ".txt")
        boxes    = images_data[fname].get("boxes", [])

        lines = []
        for box in boxes:
            cls_name = box["cls"]
            cls_id   = CLS_TO_ID[cls_name]
            x, y, w, h = box["x"], box["y"], box["w"], box["h"]
            lines.append(f"{cls_id} {x:.10f} {y:.10f} {w:.10f} {h:.10f}")

            # Accumulate statistics
            stats["box_counts"][split_name][cls_name] += 1
            stats["box_counts"][split_name]["total"]   += 1
            stats["class_totals"][cls_name]            += 1

        with open(lbl_path, "w", encoding="utf-8") as f:
            f.write("\n".join(lines))
            if lines:
                f.write("\n")

        stats["counts"][split_name] += 1

    return stats

def print_stats(stats):
    total_imgs = sum(stats["counts"].values())
    total_boxes = sum(bc["total"] for bc in stats["box_counts"].values())
    print("\n=== Export Statistics ===")
    print(f"  Images:  train={stats['counts']['train']}  "
          f"val={stats['counts']['val']}  test={stats['counts']['test']}  "
          f"total={total_imgs}")
    print(f"  Boxes:   total={total_boxes}")
    for split in ("train", "val", "test"):
        bc = stats["box_counts"][split]
        print(f"    {split:5s}: bottle={bc['bottle']}  "
              f"cap={bc['cap']}  label={bc['label']}  "
              f"total={bc['total']}")
    ct = stats["class_totals"]
    print(f"  Class totals: bottle={ct['bottle']}  "
          f"cap={ct['cap']}  label={ct['label']}")

    if stats["missing_images"]:
        print(f"\n  !! Missing source images ({len(stats['missing_images'])}):")
        for f in stats["missing_images"]:
            print(f"       {f}")
    if stats["errors"]:
        print(f"\n  !! Errors ({len(stats['errors'])}):")
        for e in stats["errors"]:
            print(f"       {e}")

def sanity_check(stats):
    """Quick pre-validation sanity check during export."""
    issues = []
    for split, exp in [("train", EXPECTED["train"]),
                       ("val",   EXPECTED["val"]),
                       ("test",  EXPECTED["test"])]:
        got = stats["counts"][split]
        if got != exp:
            issues.append(f"Image count {split}: expected {exp}, got {got}")

    total_boxes = sum(bc["total"] for bc in stats["box_counts"].values())
    if total_boxes != EXPECTED["boxes"]:
        issues.append(f"Total boxes: expected {EXPECTED['boxes']}, got {total_boxes}")

    if issues:
        print("\n[SANITY] Issues found:")
        for i in issues:
            print(f"  - {i}")
        return False
    else:
        print("\n[SANITY] All counts match expected values.")
        return True

def main():
    print("=" * 60)
    print("Stage 2D-B — YOLO Export")
    print(f"Timestamp: {datetime.datetime.now().isoformat()}")
    print("=" * 60)

    # 1. Load data
    print("[LOAD] Loading annotations.json ...")
    annotations = load_json(ANNOT_PATH)

    print("[LOAD] Loading split.json ...")
    split_data = load_json(SPLIT_PATH)

    # 2. Build split map
    split_map = build_split_map(split_data)
    print(f"[SPLIT] {len(split_map)} images in split map.")

    # 3. Create directories
    create_dirs()

    # 4. Export images + labels
    print("[EXPORT] Copying images and writing YOLO labels ...")
    stats = export(annotations, split_map)
    print_stats(stats)

    # 5. Write data.yaml
    write_data_yaml()

    # 6. Sanity check
    passed = sanity_check(stats)

    print("\n" + "=" * 60)
    if not stats["errors"] and passed:
        print("EXPORT COMPLETE — no errors, sanity checks passed.")
        print(f"Output: {EXPORT_DIR}")
    else:
        print("EXPORT COMPLETE WITH ISSUES — see above.")
        sys.exit(1)

if __name__ == "__main__":
    main()
